/// The square the colour picker shows for a colour: its top, across the middle and right.
pub fn xmb_swatch(colour: u32) -> [u8; 3] {
    let e = entry(colour);
    let (a, b) = (e[0][1], e[0][2]);
    [0, 1, 2].map(|i| ((a[i] as u16 + b[i] as u16) / 2) as u8)
}

/// The date orders Date Format offers: month first, day first, year first.
pub const XMB_DATE_FORMATS: [&str; 3] = ["MM/DD/YYYY", "DD/MM/YYYY", "YYYY/MM/DD"];

/// The time formats Time Format offers.
pub const XMB_TIME_FORMATS: [&str; 2] = ["12-Hour Clock", "24-Hour Clock"];

fn time_text(wall_secs: i64, clock24: bool) -> String {
    let secs = wall_secs.rem_euclid(86_400);
    let (h, m) = (secs / 3600, secs / 60 % 60);
    if clock24 {
        return format!("{h}:{m:02}");
    }
    let (h12, half) = match h {
        0 => (12, "AM"),
        1..=11 => (h, "AM"),
        12 => (12, "PM"),
        _ => (h - 12, "PM"),
    };
    format!("{h12}:{m:02} {half}")
}

/// The status bar's clock: month and day in the chosen order, then the time.
pub fn xmb_clock_text(wall_secs: i64, date_format: u8, clock24: bool) -> String {
    let (_, month, day) = civil(wall_secs);
    let date = match date_format {
        1 => format!("{day}/{month}"),
        _ => format!("{month}/{day}"),
    };
    format!("{date} {}", time_text(wall_secs, clock24))
}

/// The full date and time, as the Date & Time row shows it.
pub fn xmb_date_time_text(wall_secs: i64, date_format: u8, clock24: bool) -> String {
    let (year, month, day) = civil(wall_secs);
    let date = match date_format {
        1 => format!("{day:02}/{month:02}/{year}"),
        2 => format!("{year}/{month:02}/{day:02}"),
        _ => format!("{month:02}/{day:02}/{year}"),
    };
    format!("{date} {}", time_text(wall_secs, clock24))
}

/// Year, month and day of a local wall-clock time in seconds since the epoch.
pub fn civil(wall_secs: i64) -> (i64, u32, u32) {
    let z = wall_secs.div_euclid(86_400) + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let month = (if mp < 10 { mp + 3 } else { mp - 9 }) as u32;
    let year = yoe + era * 400 + i64::from(month <= 2);
    (year, month, day)
}

/// Month (1..=12) of a local wall-clock time in seconds since the epoch.
pub fn month_of(wall_secs: i64) -> u32 {
    let z = wall_secs.div_euclid(86_400) + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    (if mp < 10 { mp + 3 } else { mp - 9 }) as u32
}


